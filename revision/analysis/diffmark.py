r"""Build a marked-up (tracked-changes) LaTeX manuscript from two versions.

    python diffmark.py <old.tex> <new.tex> <out.tex>

Word-level diff of the document body, in the spirit of latexdiff:
  added text      -> blue wavy underline   (\DIFadd)
  deleted text    -> red strikethrough     (\DIFdel)
  new or revised table/figure/equation floats are rendered entirely in blue
LaTeX commands, citations, references and math are kept atomic so the output
compiles; deleted commands without visible text (labels, citations) are
dropped rather than struck through.
"""

import difflib
import re
import sys

ATOMIC_ENV = r"\\begin\{(?P<envname>table|figure|equation)\}.*?\\end\{(?P=envname)\}"
TOKEN_RE = re.compile(
    r"(?P<env>" + ATOMIC_ENV + r")"
    r"|(?P<math>\$[^$]*\$)"
    r"|(?P<sec>\\(?:section|subsection|paragraph)\*\{[^{}]*\})"
    r"|(?P<cmd>\\[a-zA-Z]+\*?(?:\[[^\]]*\])?(?:\{(?:[^{}]|\{[^{}]*\})*\})*)"
    r"|(?P<sym>\\[^a-zA-Z])"
    r"|(?P<brace>[{}])"
    r"|(?P<tilde>~)"
    r"|(?P<word>(?:[^\s\\{}$%~]|\{,\})+)",
    re.S,
)

PREAMBLE_ADD = r"""
% tracked-changes markup (generated by revision/analysis/diffmark.py)
\usepackage[normalem]{ulem}
\providecommand{\DIFadd}[1]{{\color{blue}\uwave{#1}}}
\providecommand{\DIFdel}[1]{{\color{red}\sout{#1}}}
"""


def strip_comments(text: str) -> str:
    return re.sub(r"(?<!\\)%.*", "", text)


def tokenize(text: str):
    toks, pos = [], 0
    for m in TOKEN_RE.finditer(text):
        ws = text[pos:m.start()]
        toks.append((m.lastgroup, m.group(0), ws))
        pos = m.end()
    return toks


def norm_ws(ws: str) -> str:
    if ws.count("\n") >= 2:
        return "\n\n"
    return " " if ws else ""


def color_float(block: str) -> str:
    first_nl = block.index("\n") if "\n" in block else len(block)
    return block[:first_nl] + "\n\\color{blue}" + block[first_nl:]


def emit(kind, text, ws, mode, out):
    """mode: 'eq', 'add', 'del'."""
    if mode == "eq":
        out.append(ws + text)
        return
    if mode == "add":
        if kind == "env":
            out.append(ws + color_float(text))
        elif kind == "sec":
            head, body = text.split("{", 1)
            out.append(ws + head + "{{\\color{blue}" + body[:-1] + "}}")
        elif kind in ("brace", "tilde", "sym"):
            out.append(ws + text)
        else:
            out.append(ws + "{\\color{blue}" + text + "}")
        return
    # deletions
    if kind == "math":
        out.append(ws + "\\DIFdel{" + text + "}")
    elif kind == "sec":
        out.append("\n\n{\\color{red}\\sout{" + text.split("{", 1)[1][:-1] + "}}\n\n")
    # other deleted atoms (floats, cites, labels, braces) are dropped


def main(old_path, new_path, out_path):
    old = open(old_path, encoding="utf-8").read()
    new = open(new_path, encoding="utf-8").read()
    start = "\\section*{Abstract}"
    end = "\\end{document}"
    o_body = strip_comments(old[old.index(start):old.index(end)])
    n_head = new[:new.index(start)]
    n_body = strip_comments(new[new.index(start):new.index(end)])

    ot, nt = tokenize(o_body), tokenize(n_body)
    sm = difflib.SequenceMatcher(a=[t[1] for t in ot], b=[t[1] for t in nt], autojunk=False)
    out = []
    for op, i1, i2, j1, j2 in sm.get_opcodes():
        if op == "equal":
            for k, s, ws in nt[j1:j2]:
                emit(k, s, ws, "eq", out)
            continue
        # deletions first, then additions; group plain words into one wrapper
        for mode, seq in (("del", ot[i1:i2]), ("add", nt[j1:j2])):
            run, run_ws = [], None
            for k, s, ws in seq:
                if k == "word" or (mode == "add" and k == "math"):
                    if run and mode == "add" and norm_ws(ws) == "\n\n":
                        out.append(run_ws + "\\DIFadd{" + "".join(run) + "}")
                        run = []
                    if not run:
                        run_ws = norm_ws(ws) if mode == "del" else ws
                        run.append(s)
                    else:
                        run.append((" " if ws else "") + s)
                    continue
                if run:
                    macro = "\\DIFadd" if mode == "add" else "\\DIFdel"
                    out.append(run_ws + macro + "{" + "".join(run) + "}")
                    run = []
                emit(k, s, ws if mode == "add" else norm_ws(ws), mode, out)
            if run:
                macro = "\\DIFadd" if mode == "add" else "\\DIFdel"
                out.append(run_ws + macro + "{" + "".join(run) + "}")

    head = n_head.replace("\\begin{document}", PREAMBLE_ADD + "\n\\begin{document}", 1)
    banner = ("% Tracked-changes manuscript: blue wavy underline = added text,\n"
              "% red strikethrough = deleted text, blue floats = new or revised\n"
              "% tables and figures. Generated from revision/final_manuscript_submitted.tex\n"
              "% and final_manuscript.tex by revision/analysis/diffmark.py.\n")
    body = "".join(out)
    body = re.sub(r"\n{3,}", "\n\n", body)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(banner + head + body + "\n" + end + "\n")
    print("written", out_path)


if __name__ == "__main__":
    main(*sys.argv[1:4])
